-- Supermarket re-sorting (step 1: proposal only — nothing on the live shop changes).
-- Rules live in a private schema (ds_work, not exposed to the app's API). Each product gets the rule with the
-- lowest priority whose category / name patterns match. Names are normalised first (ی→ي, ک→ك, أإآ→ا, ى→ي, ة→ه).

create schema if not exists ds_work;
revoke all on schema ds_work from public, anon, authenticated;

create or replace function ds_work.norm(t text) returns text language sql immutable as $$
  select regexp_replace(lower(translate(coalesce(t,''), 'یکأإآىةۀ', 'يكااايهه')), '[ًٌٍَُِّْـ]', '', 'g')
$$;

create table if not exists ds_work.sm_rules(pri int primary key, cat text, pat text, notpat text, aisle text not null, sub text not null);

