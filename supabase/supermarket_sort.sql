-- the proposal: one row per active product
create or replace view ds_work.sm_proposal as
select p.id, p.name, p.category_name as old_category, r.aisle, case when r.sub = '=' then p.category_name else r.sub end as sub, r.pri
from public.supermarket_products p
left join lateral (
  select * from ds_work.sm_rules r
  where (r.cat is null or p.category_name ~ r.cat)
    and (r.pat is null or ds_work.norm(p.name) ~ r.pat)
    and (r.notpat is null or ds_work.norm(p.name) !~ r.notpat)
  order by r.pri limit 1) r on true
where p.is_active;
